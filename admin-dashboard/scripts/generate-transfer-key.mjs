#!/usr/bin/env node
/**
 * Generates a DEVELOPMENT unit transfer key (32 random bytes) and stores it in
 * .env.local (git-ignored). Tablets receive it at sign-in and use it to
 * encrypt casualty records handed from one tablet to another. The key is
 * never printed.
 *
 *   npm run transfer:keygen                          # key ID dev-transfer-01
 *   npm run transfer:keygen -- --key-id dev-transfer-02 --force   # rotate
 *
 * After generating: restart the dashboard, then sign in online on every
 * tablet (or run `npm run mobile:provision` for the demo build).
 */
import { randomBytes } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const flag = name => args.includes(name);
const option = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};

const keyId = option("--key-id", "dev-transfer-01");
const force = flag("--force");
const envFile = path.resolve(process.cwd(), ".env.local");

if (!/^[a-z0-9][a-z0-9-]{0,31}$/.test(keyId)) {
  console.error("Key ID must be 1-32 characters: lower-case letters, digits and hyphens.");
  process.exit(1);
}

const existing = existsSync(envFile) ? readFileSync(envFile, "utf8") : "";
if (/^CASEVAC_TRANSFER_KEY=\S+/m.test(existing) && !force) {
  console.error(
    ".env.local already contains a transfer key. Re-run with --force to replace it\n" +
      "(tablets holding the old key can no longer exchange records until they sign in again).",
  );
  process.exit(1);
}

const kept = existing
  .split(/\r?\n/)
  .filter(line => !/^CASEVAC_TRANSFER_(KEY_ID|KEY)=/.test(line))
  .join("\n")
  .replace(/\n*$/, "");
const block = [
  "",
  "# DEVELOPMENT unit transfer key (32 bytes, base64url). Generated by npm run transfer:keygen.",
  `CASEVAC_TRANSFER_KEY_ID=${keyId}`,
  `CASEVAC_TRANSFER_KEY=${randomBytes(32).toString("base64url")}`,
  "",
].join("\n");

writeFileSync(envFile, `${kept}${block}`);
console.log(`Transfer key ${keyId} written to .env.local. Restart the dashboard to use it.`);
