#!/usr/bin/env node
/**
 * Generates a DEVELOPMENT Ed25519 QR issuer key and stores it in .env.local
 * (git-ignored). The private key is never printed.
 *
 *   npm run issuer:keygen                       # key ID dev-issuer-01
 *   npm run issuer:keygen -- --key-id dev-issuer-02 --force   # rotate
 *
 * After generating: restart the dashboard, reissue existing QR codes and run
 * `npm run mobile:provision` so phones trust the new public key.
 *
 * Not for production: a production issuer key belongs in a protected signing
 * service (HSM/KMS), never in an environment file on a web server.
 */
import { generateKeyPairSync } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const args = process.argv.slice(2);
const flag = name => args.includes(name);
const option = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};

const keyId = option("--key-id", "dev-issuer-01");
const force = flag("--force");
const envFile = path.resolve(process.cwd(), ".env.local");

if (!/^[a-z0-9][a-z0-9-]{0,31}$/.test(keyId)) {
  console.error("Key ID must be 1-32 characters: lower-case letters, digits and hyphens.");
  process.exit(1);
}

const existing = existsSync(envFile) ? readFileSync(envFile, "utf8") : "";
const hasKey = /^CASEVAC_QR_ISSUER_PRIVATE_KEY=\S+/m.test(existing);
if (hasKey && !force) {
  console.error(
    ".env.local already contains a QR issuer key. Re-run with --force to replace it\n" +
      "(every QR signed with the old key must then be reissued).",
  );
  process.exit(1);
}

const { privateKey, publicKey } = generateKeyPairSync("ed25519");
const privateDer = privateKey.export({ format: "der", type: "pkcs8" }).toString("base64url");
const publicRaw = publicKey.export({ format: "jwk" }).x;

const kept = existing
  .split(/\r?\n/)
  .filter(line => !/^CASEVAC_QR_ISSUER_(KEY_ID|PRIVATE_KEY)=/.test(line))
  .join("\n")
  .replace(/\n*$/, "");
const block = [
  "",
  "# DEVELOPMENT QR issuer key (Ed25519, PKCS#8 base64url). Generated by npm run issuer:keygen.",
  `CASEVAC_QR_ISSUER_KEY_ID=${keyId}`,
  `CASEVAC_QR_ISSUER_PRIVATE_KEY=${privateDer}`,
  "",
].join("\n");
writeFileSync(envFile, (kept ? kept + "\n" : "") + block, { encoding: "utf8" });

console.log(`Development QR issuer key written to ${envFile}`);
console.log(`  Key ID:     ${keyId}`);
console.log(`  Public key: ${publicRaw}`);
console.log("Next: restart the dashboard, reissue QR codes, then run `npm run mobile:provision`.");
